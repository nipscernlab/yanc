#!/usr/bin/env python3
"""Generated C± tests for the emitters of cmmcomp no hand-written test reaches
(issue #69, Scripts/cmm_cov.sh). Each family writes one test under
Compilers/CMMComp/Tests/ and its expected output, computed here in Python
from the same values, apart from YANC: so a call these tests reach counts as
verified (Compilers/CMMComp/Tests/verified.txt).

The values are small integers, or floats whose truncation is plain, so the
expected output does not depend on the float format's rounding. out() writes
an int, fout() a float truncated to an int.

usage: python3 Scripts/cov_tests.py [repo-root] --write   write the tests and their golden_sim
       python3 Scripts/cov_tests.py [repo-root] --check   the golden_sim of each is what it computes
"""
import os
import sys

HEAD = "#NUBITS 32\n#NBMANT 23\n#NBEXPO 8\n#NUIOIN 1\n#NUIOOU 1\n\n"


def trunc(x):
    return int(x)           # toward zero, as F2I


# ---------------------------------------------------------------------------
# matrix reads: arr_2d2exp, every form of each index on int, float and comp
# matrices, read alone and with a value pending in the accumulator
# ---------------------------------------------------------------------------
R, C = 3, 4
MI = [[10 * r + c + 1 for c in range(C)] for r in range(R)]
MF = [[100 + 10 * r + c for c in range(C)] for r in range(R)]
MC = [[complex(10 * r + c, -(10 * r + c) - 1) for c in range(C)] for r in range(R)]

PAIRS = [(1, 2), (2, 3), (2, 1), (1, 3)]

# an index form: its C± text for the value k, and its value as an index
FORMS = [
    ("int var",    lambda k: "n%d" % k),
    ("int acc",    lambda k: "(n%d+z0)" % k),
    ("int lit",    lambda k: "%d" % k),
    ("float var",  lambda k: "f%d" % k),
    ("float acc",  lambda k: "(f%d+fz)" % k),
    ("comp const", lambda k: "(%d+9i)" % k),
    ("comp acc",   lambda k: "(c%d*one)" % k),
    ("comp var",   lambda k: "c%d" % k),
]
# the variables the forms read: nk = k, fk = k + 0.7 (truncated to k),
# ck = k + (k+3)i (its real part, k, is the index), z0 = 0, fz = 0.0, one = 1
DECL = ("    int n0; int n1; int n2; int n3; int z0;\n"
        "    float f0; float f1; float f2; float f3; float fz;\n"
        "    comp c0; comp c1; comp c2; comp c3; comp one;\n"
        "    int x; float y; comp w;\n"
        "    n0 = 0; n1 = 1; n2 = 2; n3 = 3; z0 = 0;\n"
        "    f0 = 0.7; f1 = 1.7; f2 = 2.7; f3 = 3.7; fz = 0.0;\n"
        "    c0 = 0+3i; c1 = 1+4i; c2 = 2+5i; c3 = 3+6i; one = 1+0i;\n")


def arr2d_read():
    body, out = [], []
    j = 0
    for pending in (0, 1):
        for fa_name, fa in FORMS:
            for fb_name, fb in FORMS:
                # never 0 (converting 0 hides a wrong conversion) and the row
                # never equal to the column (a swap shows)
                r, c = PAIRS[j % len(PAIRS)]
                j += 1
                ia, ib = fa(r), fb(c)
                # int matrix
                if pending:
                    body.append("    x = 1000 + mi[%s][%s]; out(0, x);" % (ia, ib))
                    out.append(1000 + MI[r][c])
                else:
                    body.append("    x = mi[%s][%s]; out(0, x);" % (ia, ib))
                    out.append(MI[r][c])
                # float matrix
                if pending:
                    body.append("    y = 1000.0 + mf[%s][%s]; fout(0, y);" % (ia, ib))
                    out.append(trunc(1000 + MF[r][c]))
                else:
                    body.append("    y = mf[%s][%s]; fout(0, y);" % (ia, ib))
                    out.append(trunc(MF[r][c]))
                # comp matrix
                v = MC[r][c] + (complex(100, 100) if pending else 0)
                body.append("    w = %smc[%s][%s]; fout(0, real(w)); fout(0, imag(w));"
                            % ("(100+100i) + " if pending else "", ia, ib))
                out += [trunc(v.real), trunc(v.imag)]
    ini = lambda m, f: "{" + ", ".join("{" + ", ".join(f(v) for v in row) + "}" for row in m) + "}"
    src = (HEAD +
           "// Generated by Scripts/cov_tests.py (issue #69): every form of each index\n"
           "// of a matrix read (int, float and comp; in memory, in the accumulator, a\n"
           "// literal) on int, float and comp matrices, alone and with a value pending\n"
           "// in the accumulator. A float index is truncated, a comp one gives its real\n"
           "// part. The expected output is computed by the script, apart from YANC.\n\n"
           "int   mi[3][4] = %s;\n" % ini(MI, str) +
           "float mf[3][4] = %s;\n" % ini(MF, lambda v: "%d.0" % v) +
           "comp  mc[3][4] = %s;\n\n" % ini(MC, lambda v: "%d%+di" % (v.real, v.imag)) +
           "void main()\n{\n" + DECL + "\n".join(body) + "\n}\n")
    return "cmm_cov_arr2d_rd", src, out


# ---------------------------------------------------------------------------
# writes: the address of a store (arr_1d_index, arr_2d_index), the store of
# each kind of value into each kind of array with its conversion (ass_array),
# and ++ on an element (ass_aplus, ass_apl2d). Every store is read back
# through a path the read test verifies (int variables as indexes). Each
# store writes a value that is new to the array, so a store that does not
# happen shows; floats are printed doubled, so that a float stored as a
# truncated int shows too.
# ---------------------------------------------------------------------------

# a value form: its C± text for the number K, its value, and its type
VALS = [
    ("int var",    lambda K: "iv",                      lambda K: K,                      "i"),
    ("int acc",    lambda K: "(iv+z0)",                 lambda K: K,                      "i"),
    ("int lit",    lambda K: "%d" % K,                  lambda K: K,                      "i"),
    ("float var",  lambda K: "fv",                      lambda K: K + 0.5,                "f"),
    ("float acc",  lambda K: "(fv+fz)",                 lambda K: K + 0.5,                "f"),
    ("float lit",  lambda K: "%d.5" % K,                lambda K: K + 0.5,                "f"),
    ("comp var",   lambda K: "cv",                      lambda K: complex(K, K + 50),     "c"),
    ("comp acc",   lambda K: "(cv*one)",                lambda K: complex(K, K + 50),     "c"),
    ("comp lit",   lambda K: "(%d+%di)" % (K, K + 50),  lambda K: complex(K, K + 50),     "c"),
]
SET_VARS = "    iv = %d; fv = %d.5; cv = %d+%di;"


def stored(value, kind):
    """the value an array of kind i, f or c holds after the store"""
    re = value.real if isinstance(value, complex) else value
    if kind == "i":
        return trunc(re)
    if kind == "f":
        return float(re)
    return value if isinstance(value, complex) else complex(value, 0)


def shown(v, kind):
    """what the read back prints: an int, a float doubled, a comp's parts doubled"""
    if kind == "i":
        return [v]
    if kind == "f":
        return [trunc(2 * v)]
    return [trunc(2 * v.real), trunc(2 * v.imag)]


def show_stmt(ref, kind):
    if kind == "i":
        return "out(0, %s);" % ref
    if kind == "f":
        return "fout(0, 2.0*%s);" % ref
    return "w = %s; fout(0, 2.0*real(w)); fout(0, 2.0*imag(w));" % ref


DECL_W = DECL + "    int iv; float fv; comp cv;\n"
KINDS = (("i", "int  "), ("f", "float"), ("c", "comp "))


def arr2d_write():
    m = {k: [[None] * C for _ in range(R)] for k, _ in KINDS}
    body, out = [], []
    K = 100

    def store(kind, ia, ib, r, c, vtext, value):
        nonlocal K
        body.append(SET_VARS % (K, K, K, K + 50))
        body.append("    m%s[%s][%s] = %s;" % (kind, ia, ib, vtext))
        m[kind][r][c] = stored(value, kind)
        body.append("    " + show_stmt("m%s[n%d][n%d]" % (kind, r, c), kind))
        out.extend(shown(m[kind][r][c], kind))
        K += 1

    j = 0
    for kind, _ in KINDS:                       # every index form, the value of the array's type
        own = {"i": VALS[0], "f": VALS[3], "c": VALS[6]}[kind]
        for fa_name, fa in FORMS:
            for fb_name, fb in FORMS:
                r, c = PAIRS[j % len(PAIRS)]; j += 1
                store(kind, fa(r), fb(c), r, c, own[1](K), own[2](K))
    for kind, _ in KINDS:                       # every value form, two index forms
        for vname, vtext, vval, vtype in VALS:
            for fa, fb in ((FORMS[0][1], FORMS[0][1]), (FORMS[1][1], FORMS[1][1])):
                r, c = PAIRS[j % len(PAIRS)]; j += 1
                store(kind, fa(r), fb(c), r, c, vtext(K), vval(K))
    for kind in ("i", "f"):                     # ++ with every index form
        for fa_name, fa in FORMS:
            for fb_name, fb in FORMS:
                r, c = PAIRS[j % len(PAIRS)]; j += 1
                body.append("    m%s[%s][%s]++;" % (kind, fa(r), fb(c)))
                m[kind][r][c] = m[kind][r][c] + 1
                body.append("    " + show_stmt("m%s[n%d][n%d]" % (kind, r, c), kind))
                out.extend(shown(m[kind][r][c], kind))
    decl = "".join("%s m%s[3][4];\n" % (t, k) for k, t in KINDS)
    src = (HEAD +
           "// Generated by Scripts/cov_tests.py (issue #69): stores into int, float and\n"
           "// comp matrices with every form of each index, every kind of value (int,\n"
           "// float, comp; in memory, in the accumulator, a literal) with its conversion,\n"
           "// and ++ on an element; each store read back. Floats are printed doubled.\n"
           "// The expected output is computed by the script, apart from YANC.\n\n" +
           decl + "\nvoid main()\n{\n" + DECL_W + "\n".join(body) + "\n}\n")
    return "cmm_cov_arr2d_wr", src, out


def arr1d():
    N = 8
    rev = lambda k: int("{:03b}".format(k)[::-1], 2)       # #FFTSIZ 3, the default
    init = {"i": [3 * k + 1 for k in range(N)],
            "f": [50.0 + k for k in range(N)],
            "c": [complex(20 + k, -k - 1) for k in range(N)]}
    v = {k: list(init[k]) for k, _ in KINDS}
    body, out = [], []
    K = 300
    idx = [1, 2, 3]                                         # never 0 (the forms read n1..n3, f1..f3, c1..c3)
    fidx = [1, 3]                                           # their reversals 4 and 6: never the index itself
    j = 0
    for pending in (0, 1):                                  # reads, every index form
        for kind, _ in KINDS:
            for fname, f in FORMS:
                k = idx[j % len(idx)]; j += 1
                if kind == "i":
                    body.append("    x = %sv%s[%s]; out(0, x);" % ("1000 + " if pending else "", kind, f(k)))
                    out.append(v[kind][k] + (1000 if pending else 0))
                elif kind == "f":
                    body.append("    y = %sv%s[%s]; fout(0, 2.0*y);" % ("1000.0 + " if pending else "", kind, f(k)))
                    out.append(trunc(2 * (v[kind][k] + (1000 if pending else 0))))
                else:
                    body.append("    w = %sv%s[%s]; fout(0, 2.0*real(w)); fout(0, 2.0*imag(w));"
                                % ("(100+100i) + " if pending else "", kind, f(k)))
                    z = v[kind][k] + (complex(100, 100) if pending else 0)
                    out += [trunc(2 * z.real), trunc(2 * z.imag)]

    def store(kind, itext, k, vtext, value, fft=False):
        nonlocal K
        body.append(SET_VARS % (K, K, K, K + 50))
        body.append("    v%s[%s%s = %s;" % (kind, itext, ")" if fft else "]", vtext))
        at = rev(k) if fft else k
        v[kind][at] = stored(value, kind)
        body.append("    " + show_stmt("v%s[n%d]" % (kind, at) if at < 4 else "v%s[%d]" % (kind, at), kind))
        out.extend(shown(v[kind][at], kind))
        K += 1

    for kind, _ in KINDS:                                   # stores, every index form
        own = {"i": VALS[0], "f": VALS[3], "c": VALS[6]}[kind]
        for fname, f in FORMS:
            k = idx[j % len(idx)]; j += 1
            store(kind, f(k), k, own[1](K), own[2](K))
    for kind, _ in KINDS:                                   # stores, every value form
        for vname, vtext, vval, vtype in VALS:
            for f in (FORMS[0][1], FORMS[1][1]):
                k = idx[j % len(idx)]; j += 1
                store(kind, f(k), k, vtext(K), vval(K))
    for kind in ("i", "f"):                                 # ++, every index form
        for fname, f in FORMS:
            k = idx[j % len(idx)]; j += 1
            body.append("    v%s[%s]++;" % (kind, f(k)))
            v[kind][k] += 1
            body.append("    " + show_stmt("v%s[%d]" % (kind, k), kind))
            out.extend(shown(v[kind][k], kind))
    for kind, _ in KINDS:                                   # the bit-reversed index, read and store
        for f in (FORMS[0][1], FORMS[1][1]):
            k = fidx[j % len(fidx)]; j += 1
            if kind == "i":
                body.append("    x = v%s[%s); out(0, x);" % (kind, f(k)))
            elif kind == "f":
                body.append("    y = v%s[%s); fout(0, 2.0*y);" % (kind, f(k)))
            else:
                body.append("    w = v%s[%s); fout(0, 2.0*real(w)); fout(0, 2.0*imag(w));" % (kind, f(k)))
            out.extend(shown(v[kind][rev(k)], kind))
            own = {"i": VALS[0], "f": VALS[3], "c": VALS[6]}[kind]
            store(kind, f(k), k, own[1](K), own[2](K), fft=True)
    fmt = {"i": str, "f": lambda x: "%d.0" % x, "c": lambda z: "%d%+di" % (z.real, z.imag)}
    decl = "".join("%s v%s[8] = {%s};\n" % (t, k, ", ".join(fmt[k](x) for x in init[k])) for k, t in KINDS)
    src = (HEAD +
           "// Generated by Scripts/cov_tests.py (issue #69): reads of int, float and\n"
           "// comp vectors with every form of the index, alone and with a value pending\n"
           "// in the accumulator; stores with every index form and every kind of value;\n"
           "// ++ on an element; the bit-reversed index v[k) (#FFTSIZ 3) read and stored.\n"
           "// Each store is read back; floats are printed doubled. The expected output\n"
           "// is computed by the script, apart from YANC.\n\n" +
           decl + "\nvoid main()\n{\n" + DECL_W + "\n".join(body) + "\n}\n")
    return "cmm_cov_arr1d", src, out


# ---------------------------------------------------------------------------
# operators (oper.c): + - * / between every pair of operand forms, alone and
# with a value pending in the accumulator; % shifts and bitwise between ints;
# comparisons and logical operators between ints and floats; unary - ! ~
# ---------------------------------------------------------------------------

# operand forms: (text, value). L for the left operand, Rr for the right
def forms(i, f, c, s):
    """the nine forms of an operand: int, float and comp, each in memory, in
    the accumulator and a literal; s is the suffix of its variables"""
    return [
        ("i" + s,              i, "i"), ("(i%s+z0)" % s, i, "i"), ("%d" % i, i, "i"),
        ("f" + s,              f, "f"), ("(f%s+fz)" % s, f, "f"), (repr(f), f, "f"),
        ("c" + s,              c, "c"), ("(c%s*one)" % s, c, "c"),
        ("(%g%+gi)" % (c.real, c.imag), c, "c"),
    ]


LV = (101, 2.5, complex(3, 2))
RV = (3, 1.25, complex(1, -1))
L = forms(*LV, "a")
Rr = forms(*RV, "b")


def promote(ta, tb):
    return "c" if "c" in (ta, tb) else "f" if "f" in (ta, tb) else "i"


def cdiv(a, b):                       # C's int division and remainder: toward zero
    q = abs(a) // abs(b) * (1 if (a < 0) == (b < 0) else -1)
    return q, a - q * b


def emit_result(body, out, expr, value, t):
    """assign to x, y or w and print: an int, a float times 4, a comp's parts times 4"""
    if t == "i":
        body.append("    x = %s; out(0, x);" % expr)
        out.append(int(value))
    elif t == "f":
        body.append("    y = %s; fout(0, 4.0*y);" % expr)
        out.append(safe_trunc(4 * value))
    else:
        body.append("    w = %s; fout(0, 4.0*real(w)); fout(0, 4.0*imag(w));" % expr)
        out += [safe_trunc(4 * value.real), safe_trunc(4 * value.imag)]


def safe_trunc(v):
    # a value whose truncation a rounding of the last bit could flip is not a
    # fair test: refuse it here, so the generator is changed, not the test
    if abs(v - round(v)) > 1e-9 and abs(v - round(v)) < 1e-3:
        raise ValueError("value %r is too close to an integer to truncate safely" % v)
    return trunc(v)


def arith(op, a, b, ta, tb):
    t = promote(ta, tb)
    if t == "i":
        if op == "+": return a + b
        if op == "-": return a - b
        if op == "*": return a * b
        return cdiv(a, b)[0]
    a, b = (complex(a), complex(b)) if t == "c" else (float(a), float(b))
    return {"+": a + b, "-": a - b, "*": a * b, "/": a / b}[op]


DECL_OPS = ("    int ia; int ib; int z0; int pa; int x;\n"
            "    float fa; float fb; float fz; float pf; float y;\n"
            "    comp ca; comp cb; comp one; comp pc; comp w;\n"
            "    ia = 101; ib = 3; z0 = 0; pa = 1000;\n"
            "    fa = 2.5; fb = 1.25; fz = 0.0; pf = 1000.0;\n"
            "    ca = 3+2i; cb = 1-1i; one = 1+0i; pc = 100+100i;\n")
PEND = {"i": ("(pa+z0) + ", 1000), "f": ("(pf+fz) + ", 1000.0), "c": ("(pc*one) + ", complex(100, 100))}


def ops():
    body, out = [], []
    for op in "+-*/":                                   # every pair, alone and pending
        for pending in (0, 1):
            for at, av, ta in L:
                for bt, bv, tb in Rr:
                    t = promote(ta, tb)
                    v = arith(op, av, bv, ta, tb)
                    e = "%s %s %s" % (at, op, bt)
                    if pending:
                        p, pv = PEND[t]
                        e, v = p + "(" + e + ")", pv + v
                    emit_result(body, out, e, v, t)
    ints_l, ints_r = [x for x in L if x[2] == "i"], [x for x in Rr if x[2] == "i"]
    for at, av, _ in ints_l:                            # % shifts bitwise, ints
        for bt, bv, _ in ints_r:
            for op, f in (("%", lambda a, b: cdiv(a, b)[1]), ("<<", lambda a, b: a << b),
                          (">>", lambda a, b: a >> b), (">>>", lambda a, b: a >> b),
                          ("&", lambda a, b: a & b), ("|", lambda a, b: a | b), ("^", lambda a, b: a ^ b)):
                emit_result(body, out, "%s %s %s" % (at, op, bt), f(av, bv), "i")
    body.append("    x = -101 >>> 3; out(0, x);"); out.append(-13)          # the sign fill
    real_l, real_r = [x for x in L if x[2] != "c"], [x for x in Rr if x[2] != "c"]
    for at, av, _ in real_l:                            # comparisons and logical, ints and floats
        for bt, bv, _ in real_r:
            for op, f in (("<", lambda a, b: a < b), (">", lambda a, b: a > b), ("<=", lambda a, b: a <= b),
                          (">=", lambda a, b: a >= b), ("==", lambda a, b: a == b), ("!=", lambda a, b: a != b),
                          ("&&", lambda a, b: bool(a) and bool(b)), ("||", lambda a, b: bool(a) or bool(b))):
                emit_result(body, out, "%s %s %s" % (at, op, bt), int(f(av, bv)), "i")
    for at, av, ta in L:                                # unary
        emit_result(body, out, "-%s" % at, -av, ta)
        if ta != "c":
            emit_result(body, out, "!%s" % at, int(not av), "i")
        if ta == "i":
            emit_result(body, out, "~%s" % at, ~av, "i")
    src = (HEAD +
           "// Generated by Scripts/cov_tests.py (issue #69): the operators of oper.c.\n"
           "// + - * / between every pair of operands (int, float, comp; in memory, in the\n"
           "// accumulator, a literal), alone and with a value pending in the accumulator;\n"
           "// % shifts and bitwise between ints; comparisons and && || between ints and\n"
           "// floats; unary - ! ~. Floats and comp parts are printed times 4. The\n"
           "// expected output is computed by the script, apart from YANC.\n\n"
           "void main()\n{\n" + DECL_OPS + "\n".join(body) + "\n}\n")
    return "cmm_cov_ops", src, out


FAMILIES = [arr2d_read, arr2d_write, arr1d, ops]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    root = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    tests = os.path.join(root, "Compilers", "CMMComp", "Tests")
    bad = 0
    for fam in FAMILIES:
        name, src, out = fam()
        d = os.path.join(tests, name)
        text = "".join("%d\r\n" % v for v in out)
        cmm = src.replace("\n", "\r\n")
        gold = os.path.join(d, "golden_sim", "output_0.txt")
        if "--write" in sys.argv:
            os.makedirs(os.path.dirname(gold), exist_ok=True)
            open(os.path.join(d, name + ".cmm"), "w", newline="", encoding="utf-8").write(cmm)
            open(gold, "w", newline="").write(text)
            print("cov_tests: wrote %s (%d values)" % (name, len(out)))
        elif "--check" in sys.argv:
            ok = (open(os.path.join(d, name + ".cmm"), newline="", encoding="utf-8").read() == cmm
                  and open(gold, newline="").read() == text)
            print("cov_tests: %s %s" % (name, "is what the script computes (%d values)" % len(out)
                                        if ok else "DIFFERS from what the script computes"))
            bad += not ok
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
