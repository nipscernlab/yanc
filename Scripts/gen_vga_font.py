#!/usr/bin/env python3
"""Writes the font ROM of SAPHO/myVGAText.v from the Modern DOS 8x16 font.

The font: "Modern DOS" by Jayvee Enaguas, version 20190101.02, CC0 1.0
(public domain dedication). The original repository (notabug.org/HarvettFox96/
ttf-moderndos) was down on 2026-10-19; the file is taken from its read-only
mirror at the release commit:

    https://github.com/notpeter/ttf-moderndos  commit 2dfa3241120e1ca775f9ee45194f0376a0bf4030
    ttf/ModernDOS8x16.ttf   sha256 f79ebf2f0bf038dcfcb4648be794603fac902af132d8730484650f7f88431a4f

The mirror carries the CC0 1.0 LICENSE; the AUR package ttf-moderndos
(20190101.02) declares CC0-1.0 as well. docs/design/vga-text.md, decision 7.

Only the ASCII codes 32 to 126 are drawn (codes 0-31 and 127 are left empty:
the block never draws them). The glyph is rasterized at 16 pixels (ascent 12,
descent 4), one byte per pixel row, bit 7 = leftmost pixel. The ROM is an
array filled in an `initial` block and read through a register, the form
Quartus, Vivado and Yosys put in a memory block (a `case` with a registered
output stayed in logic on Quartus 24.1, 2026-10-20); only the non-zero rows
are listed, the loop before them zeroes the rest.

Usage:  python3 Scripts/gen_vga_font.py <ModernDOS8x16.ttf> [SAPHO/myVGAText.v]
Rewrites the lines between "// FONT BEGIN" and "// FONT END" in the .v.
Needs Pillow.
"""
import hashlib
import sys

from PIL import Image, ImageDraw, ImageFont

SHA256 = "f79ebf2f0bf038dcfcb4648be794603fac902af132d8730484650f7f88431a4f"
BEGIN, END = "// FONT BEGIN", "// FONT END"


def rows(font, code):
    im = Image.new("L", (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    out = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 127:
                b |= 1 << (7 - x)
        out.append(b)
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    ttf = sys.argv[1]
    vfile = sys.argv[2] if len(sys.argv) > 2 else "SAPHO/myVGAText.v"
    data = open(ttf, "rb").read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit(f"{ttf}: not the Modern DOS 8x16 of version 20190101.02 (sha256 differs)")
    font = ImageFont.truetype(ttf, 16)
    if font.getmetrics() != (12, 4):
        sys.exit(f"{ttf}: unexpected metrics {font.getmetrics()}, want (12, 4)")

    lines = ["\t// generated by Scripts/gen_vga_font.py from Modern DOS 8x16 (CC0 1.0): do not edit",
             "\tfor (fi = 0; fi < 2048; fi = fi + 1) font[fi] = 8'h00;"]
    n = 0
    for code in range(32, 127):
        r = rows(font, code)
        cells = [f"font[11'h{(code << 4) | y:03X}] = 8'h{b:02X};" for y, b in enumerate(r) if b]
        if cells:
            label = "space" if code == 32 else chr(code).replace("\\", "backslash")
            lines.append(f"\t// {code} {label}")
            for i in range(0, len(cells), 4):
                lines.append("\t" + " ".join(cells[i:i + 4]))
            n += len(cells)
    src = open(vfile, encoding="utf-8").read()
    a, b = src.index(BEGIN), src.index(END)
    a = src.index("\n", a) + 1
    b = src.rindex("\n", 0, b) + 1
    src = src[:a] + "\n".join(lines) + "\n" + src[b:]
    open(vfile, "w", encoding="utf-8", newline="").write(src)
    print(f"{vfile}: {n} non-zero font rows written")


if __name__ == "__main__":
    main()
