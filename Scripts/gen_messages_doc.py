#!/usr/bin/env python3
"""Write docs/reference/messages.md: every message the tools print, in English.

    python3 Scripts/gen_messages_doc.py [repo root]           # write the page
    python3 Scripts/gen_messages_doc.py [repo root] --check   # fail if it is stale

The source of truth is the code: the M("pt", "en") catalogs in
Compilers/{CMMComp,CPPComp,ASMComp}/Headers/messages.h. A format's %d / %s / %f / %c become <n>, <name>, <x>,
<c>. The page lists them; the hand-written docs/messages.md explains the
common ones.
"""
import os, re, sys

def c_literals(text, i):
    """Read adjacent C string literals from text[i:], skipping blanks, line
    continuations and comments; return (value, index after)."""
    out = []
    n = len(text)
    while True:
        while i < n:
            if text[i] in ' \t\r\n\\':
                i += 1
            elif text.startswith('//', i):
                j = text.find('\n', i); i = n if j < 0 else j
            elif text.startswith('/*', i):
                j = text.find('*/', i); i = n if j < 0 else j + 2
            else:
                break
        if i >= n or text[i] != '"':
            return ''.join(out), i
        i += 1
        buf = bytearray()                 # bytes: a \xHH escape is one byte of UTF-8
        while i < n and text[i] != '"':
            c = text[i]
            if c == '\\' and i + 1 < n:
                e = text[i + 1]
                if e == 'x':
                    j = i + 2
                    while j < n and j < i + 4 and text[j] in '0123456789abcdefABCDEF': j += 1
                    buf.append(int(text[i + 2:j], 16)); i = j
                    continue
                buf += {'n': '\n', 't': '\t', '"': '"', '\\': '\\', "'": "'"}.get(e, '\\' + e).encode()
                i += 2
                continue
            buf += c.encode(); i += 1
        out.append(buf.decode('utf-8', 'replace')); i += 1

def clean(s):
    s = s.strip()
    s = re.sub(r'%-?\d*l*d', '<n>', s)
    s = re.sub(r'%-?\d*\.?\d*[fg]', '<x>', s)
    s = re.sub(r'%-?\d*s', '<name>', s)
    s = s.replace('%c', '<c>').replace('%02x', '<hex>').replace('%%', '%')
    s = re.sub(r'\s*\n\s*', ' ', s)
    return s

def kind(s):
    low = s.lower()
    if low.startswith(('error', 'syntax error', 'erro')) or ': error:' in low:
        return 'Errors'
    if low.startswith(('heads up', 'warning')) or ': warning:' in low:
        return 'Warnings'
    if low.startswith('info'):
        return 'Information'
    return 'Other'

def catalog_entries(path):
    """(name, English text) of each MSG_ in an M("pt", "en") catalog"""
    text = open(path, encoding='utf-8').read()
    out = []
    for m in re.finditer(r'#define\s+(MSG_\w+)\s*\\?\s*M\(', text):
        name = m.group(1)
        if name.startswith('MSG_CLI_'):          # the -h / -V texts
            continue
        pt, i = c_literals(text, m.end())
        while i < len(text) and text[i] in ' \t\r\n\\': i += 1
        if i >= len(text) or text[i] != ',':
            continue
        en, _ = c_literals(text, i + 1)
        if en:
            out.append((name, en))
    return out

def catalog(path):
    return [clean(en) for _, en in catalog_entries(path)]

def cpp_messages(root):
    """cppcomp prints `file:line: error: <text>`: its catalog holds the text,
    and the name says which (MSG_ERR_, MSG_WARN_); the pieces built into a
    message (MSG_WHO_, MSG_WORD_, MSG_WHY_, MSG_PREFIX_) are left out"""
    msgs = []
    path = os.path.join(root, 'Compilers', 'CPPComp', 'Headers', 'messages.h')
    for name, en in catalog_entries(path):
        if name.startswith('MSG_ERR_'):
            kind_ = 'error: '
        elif name.startswith('MSG_WARN_'):
            kind_ = 'warning: '
        else:
            continue
        if en.startswith('cppcomp: '):
            en = en[len('cppcomp: '):]
        msgs.append(kind_ + clean(en))
    return msgs

def section(title, msgs, out):
    seen, uniq = set(), []
    for s in msgs:
        if s not in seen:
            seen.add(s); uniq.append(s)
    out.append(f'## {title}')
    out.append('')
    for k in ('Errors', 'Warnings', 'Information', 'Other'):
        part = [s for s in uniq if kind(s) == k]
        if k == 'Other':                  # whole messages only, not the pieces others are built from
            part = [s for s in part if s[:1].isupper()]
        if not part:
            continue
        out.append(f'### {k}')
        out.append('')
        for s in part:
            out.append('- ' + s.replace('|', '\\|').replace('*', '\\*').replace('_', '\\_'))
        out.append('')

def render(root):
    out = ['# Messages', '',
           '<!-- GENERATED by Scripts/gen_messages_doc.py from the compilers\' sources: do not edit by hand. -->', '',
           'Every message the tools print, in English, as the code writes it, with',
           '`<n>` for a number, `<name>` for a name or a text and `<x>` for a',
           'value. What the common ones mean and how to get past them is in',
           '[Messages](../messages.md).', '']
    section('cmmcomp (C±)', catalog(os.path.join(root, 'Compilers', 'CMMComp', 'Headers', 'messages.h')), out)
    section('cppcomp (C++)', cpp_messages(root), out)
    section('asmcomp', catalog(os.path.join(root, 'Compilers', 'ASMComp', 'Headers', 'messages.h')), out)
    return '\n'.join(out).rstrip('\n') + '\n'

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    root = args[0] if args else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    text = render(root)
    dest = os.path.join(root, 'docs', 'reference', 'messages.md')
    if '--check' in sys.argv:
        old = open(dest, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(dest) else ''
        if old != text:
            sys.exit('gen_messages_doc: docs/reference/messages.md is stale; run Scripts/gen_messages_doc.py')
        print('gen_messages_doc: docs/reference/messages.md matches the sources')
        return
    open(dest, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'gen_messages_doc: wrote {dest} ({text.count(chr(10) + "- ")} messages)')

if __name__ == '__main__':
    main()
